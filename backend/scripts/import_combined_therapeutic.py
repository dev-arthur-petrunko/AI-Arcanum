def delete_old_therapeutic():
    """Видалити всі колишні терапевтичні системи (крім нової) з їхніми колодами й картами."""
    db_path = Path(__file__).resolve().parents[1] / "Database" / "fortune_cards.db"
    backup = db_path.with_name(f"fortune_cards_backup_therapeutic_{datetime.now():%Y%m%d_%H%M%S}.db")
    shutil.copy2(db_path, backup)
    print(f"[backup] {backup}")

    conn = sqlite3.connect(db_path)
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        sys_ids = [r[0] for r in conn.execute(
            "SELECT id FROM systems WHERE category LIKE '%терапев%' AND name != ?", (SYSTEM_NAME,)).fetchall()]
        print(f"[delete] терапевтичних систем: {len(sys_ids)} -> {sys_ids}")
        if not sys_ids:
            return
        ph = ",".join("?" * len(sys_ids))
        deck_ids = [r[0] for r in conn.execute(
            f"SELECT id FROM decks WHERE system_id IN ({ph})", sys_ids).fetchall()] or [-1]
        ph2 = ",".join("?" * len(deck_ids))
        with conn:
            conn.execute(f"DELETE FROM cards WHERE deck_id IN ({ph2})", deck_ids)
            conn.execute(f"DELETE FROM decks WHERE id IN ({ph2})", deck_ids)
            conn.execute(f"DELETE FROM systems WHERE id IN ({ph})", sys_ids)
        print(f"[delete] колод: {len(deck_ids)}, карт видалено разом з ними.")
    finally:
        conn.close()


