def build(card: dict, kind: str, t: tuple) -> dict:
    if kind == "via":
        num, uk, en, ru, v_uk, v_code, kw, rev, mean = t
        c = {"number": num, "name": uk, "arcana_type": "Сила характеру (VIA)",
             "category": v_uk, "theme": f"VIA · {en}", "suit": en, "suit_code": v_code,
             "keywords_upright": kw, "keywords_reversed": rev, "meaning_general": mean}
    elif kind == "basic":
        num, uk, en, ru, ch_uk, ch_code, kw, rev, mean = t
        c = {"number": num, "name": uk, "arcana_type": "Канал BASIC Ph",
             "category": ch_uk, "theme": f"BASIC Ph · {en}", "suit": en, "suit_code": ch_code,
             "keywords_upright": kw, "keywords_reversed": rev, "meaning_general": mean}
    else:  # maslow
        num, uk, en, ru, l_uk, l_code, kw, rev, mean = t
        c = {"number": num, "name": uk, "arcana_type": "Потреба (Маслоу)",
             "category": l_uk, "theme": f"Маслоу · {en}", "suit": en, "suit_code": l_code,
             "keywords_upright": kw, "keywords_reversed": rev, "meaning_general": mean}
    names = {"uk": uk, "en": en, "ru": ru}
    c["translations"] = {
        "uk": {"name": names["uk"], "keywords_upright": kw, "keywords_reversed": rev},
        "en": {"name": names["en"], "keywords_upright": kw, "keywords_reversed": rev},
        "ru": {"name": names["ru"], "keywords_upright": kw, "keywords_reversed": rev},
    }
    return c


