def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    n_sys = n_deck = n_card = 0
    try:
        for d in DECKS:
            system = db.query(System).filter_by(name=d["system"]).first()
            if not system:
                system = System(name=d["system"], category=d["sys_cat"],
                                history=d["sys_history"],
                                origin_country=d["sys_origin"], approx_year=d["sys_year"],
                                translations={"uk": {"name": d["system"]},
                                              "en": {"name": d["system"]},
                                              "ru": {"name": d["system"]}})
                db.add(system)
                db.flush()
                n_sys += 1
            deck = db.query(Deck).filter_by(name=d["deck"]).first()
            fields = {
                "system_id": system.id, "author": "AI-Arcanum (навчальна колода)",
                "publisher": None, "year": None, "card_count": len(d["rows"]),
                "source_url": d["src"], "is_reference_only": False,
                "description": ("Навчальна колода за відкритим довідковим джерелом: усі карти в БД, "
                                "значення — власний переказ. Джерело вказано в профілі колоди."),
                "translations": {
                    "uk": {"name": d["deck"], "description": "Навчальна колода: переказ довідкового джерела."},
                    "en": {"name": d["deck_en"], "description": "Learning deck: own paraphrase of source."},
                    "ru": {"name": d["deck_ru"], "description": "Обучающая колода: собственный пересказ источника."}},
            }
            if deck:
                for k, v in fields.items():
                    setattr(deck, k, v)
            else:
                deck = Deck(name=d["deck"], **fields)
                db.add(deck)
                db.flush()
                n_deck += 1
            db.query(Card).filter_by(deck_id=deck.id).delete()
            db.flush()
            for t in d["rows"]:
                card = build_card(d, t)
                nm = _names(d["kind"], t, "uk")
                card["translations"] = {
                    "uk": {"name": nm, "keywords_upright": card.get("keywords_upright", "")},
                    "en": {"name": _names(d["kind"], t, "en"),
                           "keywords_upright": card.get("keywords_upright", "")},
                    "ru": {"name": _names(d["kind"], t, "ru"),
                           "keywords_upright": card.get("keywords_upright", "")},
                }
                db.add(Card(deck_id=deck.id, **card))
                n_card += 1
        db.commit()
        print(f"[second-wave] систем: {n_sys} нових, колод: {n_deck} нових, карт: {n_card}")
    finally:
        db.close()


