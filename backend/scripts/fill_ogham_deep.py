def run():
    db = SessionLocal()
    try:
        d = db.query(Deck).filter_by(id=26).first()
        n = 0
        for c in db.query(Card).filter_by(deck_id=26).all():
            letter = str(c.number).upper()
            if letter not in R:
                continue
            theme, kw_r, m_r, love, career, health = R[letter]
            c.theme = theme
            c.keywords_reversed = kw_r
            c.meaning_reversed = m_r
            c.meaning_love = love
            c.meaning_career = career
            c.meaning_health = health
            n += 1
        db.commit()
        print(f"[ogham] оновлено: {n} карт")
    finally:
        db.close()


if __name__ == "__main__":
    run()