def merge(card, lang, **fields):
    tr = dict(card.translations or {})
    block = dict(tr.get(lang, {}))
    block.update({k: v for k, v in fields.items() if v})
    tr[lang] = block
    card.translations = tr


def run():
    db = SessionLocal()
    try:
        rws = db.query(Deck).filter(Deck.name.contains("Уэйта")).first()
        n = 0
        for c in db.query(Card).filter_by(deck_id=rws.id, arcana_type="Младший аркан").all():
            dec = DECANS.get(c.suit, {}).get(c.numerology or 0)
            if dec:
                planet, zodiac = dec
                c.planet, c.zodiac_sign = planet, zodiac
                c.planet_code, c.zodiac_sign_code = PLANET_CODE[planet], ZODIAC_CODE[zodiac]
            uk_name = (c.translations or {}).get("uk", {}).get("name", "")
            try:
                rank_ru = RANKS_RU[int(str(c.number).split("-")[-1]) - 1]
            except (ValueError, IndexError):
                rank_ru = ""
            merge(c, "uk",
                  meaning_love=LOVE_SUIT_UK.get(c.suit),
                  meaning_career=CAREER_RANK_UK.get(rank_ru))
            n += 1
        db.commit()
        print(f"[minors] оновлено: {n}")
    finally:
        db.close()


if __name__ == "__main__":
    run()
